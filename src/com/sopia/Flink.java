package com.sopia;

public class Flink {
	private int id;	
	private String flname;
	private String fldesc;
	private String fhref;
	private int sort;
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getFlname() {
		return flname;
	}
	public void setFlname(String flname) {
		this.flname = flname;
	}
	public String getFldesc() {
		return fldesc;
	}
	public void setFldesc(String fldesc) {
		this.fldesc = fldesc;
	}
	public String getFhref() {
		return fhref;
	}
	public void setFhref(String fhref) {
		this.fhref = fhref;
	}
	public int getSort() {
		return sort;
	}
	public void setSort(int sort) {
		this.sort = sort;
	}
	
}
