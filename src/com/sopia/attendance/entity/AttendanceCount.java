package com.sopia.attendance.entity;

public class AttendanceCount {
	private int qinajiaCount;//请假次数
	private int qinajiaDays;//请假天数
	private int chidaoCount;//迟到次数
	private int zaotuiCount;//早退次数
	private int queqinCount;//缺勤次数
	public int getQinajiaCount() {
		return qinajiaCount;
	}
	public void setQinajiaCount(int qinajiaCount) {
		this.qinajiaCount = qinajiaCount;
	}
	public int getQinajiaDays() {
		return qinajiaDays;
	}
	public void setQinajiaDays(int qinajiaDays) {
		this.qinajiaDays = qinajiaDays;
	}
	public int getChidaoCount() {
		return chidaoCount;
	}
	public void setChidaoCount(int chidaoCount) {
		this.chidaoCount = chidaoCount;
	}
	public int getZaotuiCount() {
		return zaotuiCount;
	}
	public void setZaotuiCount(int zaotuiCount) {
		this.zaotuiCount = zaotuiCount;
	}
	public int getQueqinCount() {
		return queqinCount;
	}
	public void setQueqinCount(int queqinCount) {
		this.queqinCount = queqinCount;
	}
	
	

}
